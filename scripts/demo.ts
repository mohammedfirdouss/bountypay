import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { sign, type Fixtures } from "../lib/github.ts";

try {
  process.loadEnvFile(".env.local");
} catch {}

const { values } = parseArgs({
  options: { url: { type: "string", default: "http://localhost:3000" }, postman: { type: "boolean" } },
});
const fixtures: Fixtures = JSON.parse(readFileSync("demo/fixtures.json", "utf8"));
const DEFAULT_SECRET = "bountypay-demo-secret";
// Lets PR #10 claim issue #1 before PR #13 tries, and PR #14 get its no-PayPal notice before its comment.
const LET_EACH_DELIVERY_LAND_MS = 1500;

const AUTHOR = { login: "demo-contributor" };
const MERGED_AT = "2026-11-01T12:00:00Z";
const prUrl = (n: number) => `https://github.com/${fixtures.repo}/pull/${n}`;
const repository = { full_name: fixtures.repo };

const merge = (pr: Fixtures["prs"][number]) =>
  JSON.stringify({
    action: "closed",
    number: pr.number,
    pull_request: { number: pr.number, merged: true, title: pr.title, body: pr.body, html_url: prUrl(pr.number), user: AUTHOR },
    repository,
  });

const comment = (pr: Fixtures["prs"][number], body: string) =>
  JSON.stringify({
    action: "created",
    issue: {
      number: pr.number,
      title: pr.title,
      body: pr.body,
      user: AUTHOR,
      pull_request: { html_url: prUrl(pr.number), merged_at: MERGED_AT },
    },
    comment: { body, user: AUTHOR },
    repository,
  });

const deliveries = [
  ...fixtures.prs.map((pr) => ({ name: `PR #${pr.number}: ${pr.title}`, event: "pull_request", raw: merge(pr) })),
  ...fixtures.prs.flatMap((pr) =>
    (pr.comments ?? []).map((c) => ({ name: `PR #${pr.number}: author comments a PayPal line`, event: "issue_comment", raw: comment(pr, c) })),
  ),
  { name: `Replay of PR #${fixtures.prs[0].number}`, event: "pull_request", raw: merge(fixtures.prs[0]) },
];

if (values.postman) {
  const collection = {
    info: {
      name: "BountyPay demo",
      description:
        "Signed GitHub merge and PR comment webhooks for the BountyPay demo. Generated by `node scripts/demo.ts --postman` from demo/fixtures.json. Run the server with BOUNTYPAY_DEMO=offline (no keys) or BOUNTYPAY_DEMO=1 and set webhookSecret to your GITHUB_WEBHOOK_SECRET.",
      schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    },
    variable: [
      { key: "baseUrl", value: "http://localhost:3000" },
      { key: "webhookSecret", value: DEFAULT_SECRET },
    ],
    event: [
      {
        listen: "prerequest",
        script: {
          type: "text/javascript",
          exec: [
            "const sig = CryptoJS.HmacSHA256(pm.request.body.raw, pm.collectionVariables.get('webhookSecret')).toString(CryptoJS.enc.Hex);",
            "pm.request.headers.upsert({ key: 'X-Hub-Signature-256', value: 'sha256=' + sig });",
          ],
        },
      },
    ],
    item: deliveries.map((d) => ({
      name: d.name,
      request: {
        method: "POST",
        header: [
          { key: "Content-Type", value: "application/json" },
          { key: "X-GitHub-Event", value: d.event },
        ],
        url: { raw: "{{baseUrl}}/api/github", host: ["{{baseUrl}}"], path: ["api", "github"] },
        body: { mode: "raw", raw: d.raw, options: { raw: { language: "json" } } },
      },
    })),
  };
  writeFileSync("bountypay.postman_collection.json", JSON.stringify(collection, null, 2) + "\n");
  console.log(`wrote bountypay.postman_collection.json (${deliveries.length} requests)`);
} else {
  const secret = process.env.GITHUB_WEBHOOK_SECRET || DEFAULT_SECRET;
  for (const d of deliveries) {
    const res = await fetch(`${values.url}/api/github`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "X-GitHub-Event": d.event,
        "X-Hub-Signature-256": sign(d.raw, secret),
      },
      body: d.raw,
    });
    console.log(`${res.status} ${d.name} -> ${await res.text()}`);
    await new Promise((r) => setTimeout(r, LET_EACH_DELIVERY_LAND_MS));
  }
  console.log(`\nClaude is judging in the background. Watch ${values.url} fill in.`);
}
