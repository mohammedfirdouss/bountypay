// Posts every demo/fixtures.json PR as a signed, merged pull_request webhook, then replays the first.
//   node scripts/demo.ts [--url http://localhost:3000]
//   node scripts/demo.ts --postman   writes bountypay.postman_collection.json from the same fixtures
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { sign, type Fixtures } from "../lib/github.ts";

try {
  process.loadEnvFile(".env.local");
} catch {}

const { values } = parseArgs({
  options: { url: { type: "string", default: "http://localhost:3000" }, postman: { type: "boolean" } },
});
const fixtures: Fixtures = JSON.parse(readFileSync("demo/fixtures.json", "utf8"));
const DEFAULT_SECRET = "bountypay-demo-secret";

const deliveries = [
  ...fixtures.prs.map((pr) => ({ name: `PR #${pr.number}: ${pr.title}`, pr })),
  { name: `Replay of PR #${fixtures.prs[0].number}`, pr: fixtures.prs[0] },
].map(({ name, pr }) => ({
  name,
  raw: JSON.stringify({
    action: "closed",
    number: pr.number,
    pull_request: {
      number: pr.number,
      merged: true,
      title: pr.title,
      body: pr.body,
      html_url: `https://github.com/${fixtures.repo}/pull/${pr.number}`,
      user: { login: "demo-contributor" },
    },
    repository: { full_name: fixtures.repo },
  }),
}));

if (values.postman) {
  const collection = {
    info: {
      name: "BountyPay demo",
      description:
        "Signed GitHub merge webhooks for the BountyPay demo. Generated by `node scripts/demo.ts --postman` from demo/fixtures.json. Run the server with BOUNTYPAY_DEMO=1 and set webhookSecret to your GITHUB_WEBHOOK_SECRET.",
      schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    },
    variable: [
      { key: "baseUrl", value: "http://localhost:3000" },
      { key: "webhookSecret", value: DEFAULT_SECRET },
    ],
    event: [
      {
        listen: "prerequest",
        script: {
          type: "text/javascript",
          exec: [
            "const sig = CryptoJS.HmacSHA256(pm.request.body.raw, pm.collectionVariables.get('webhookSecret')).toString(CryptoJS.enc.Hex);",
            "pm.request.headers.upsert({ key: 'X-Hub-Signature-256', value: 'sha256=' + sig });",
          ],
        },
      },
    ],
    item: deliveries.map((d) => ({
      name: d.name,
      request: {
        method: "POST",
        header: [
          { key: "Content-Type", value: "application/json" },
          { key: "X-GitHub-Event", value: "pull_request" },
        ],
        url: { raw: "{{baseUrl}}/api/github", host: ["{{baseUrl}}"], path: ["api", "github"] },
        body: { mode: "raw", raw: d.raw, options: { raw: { language: "json" } } },
      },
    })),
  };
  writeFileSync("bountypay.postman_collection.json", JSON.stringify(collection, null, 2) + "\n");
  console.log(`wrote bountypay.postman_collection.json (${deliveries.length} requests)`);
} else {
  const secret = process.env.GITHUB_WEBHOOK_SECRET ?? DEFAULT_SECRET;
  for (const d of deliveries) {
    const res = await fetch(`${values.url}/api/github`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "X-GitHub-Event": "pull_request",
        "X-Hub-Signature-256": sign(d.raw, secret),
      },
      body: d.raw,
    });
    console.log(`${res.status} ${d.name} -> ${await res.text()}`);
    // Lets each claim land before the next delivery, so the double claim finds PR #10 already holding issue #1.
    await new Promise((r) => setTimeout(r, 1500));
  }
  console.log(`\nClaude is judging in the background. Watch ${values.url} fill in.`);
}
